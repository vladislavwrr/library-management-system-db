    b.Book_ID,
    g.Genre_ID,
    -- Ранжируем жанры для каждой книги, чтобы ограничить их количество
    ROW_NUMBER() OVER (PARTITION BY b.Book_ID ORDER BY random()) AS genre_rank
  FROM 
    Book b
  CROSS JOIN 
    Genre g
  WHERE 
    -- Условие для выбора 1-3 жанров на книгу
    (b.Book_ID * 123456 + g.Genre_ID * 789) % 50 < 3 -- Магические числа для псевдослучайности
