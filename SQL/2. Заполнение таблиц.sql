-- Заявки
WITH 
-- 1. Получаем все копии книг (10500 штук)
all_books AS (
    SELECT 
        Inventory_Number,
        ROW_NUMBER() OVER (ORDER BY Inventory_Number) AS book_seq
    FROM Book_Copy
),

-- 2. Генерируем обязательные заявки для сотрудников
employee_min_requests AS (
    SELECT 
        e.Employee_ID,
        GENERATE_SERIES(1, 150) AS request_num
    FROM Employee e
),

-- 3. Добавляем оставшиеся заявки
additional_requests AS (
    SELECT 
        e.Employee_ID,
        GENERATE_SERIES(
            1, 
            (10500 - (SELECT COUNT(*) FROM employee_min_requests)) / 
            GREATEST((SELECT COUNT(*) FROM Employee), 1)
        ) AS request_num
    FROM Employee e
),

-- 4. Объединяем все заявки сотрудников
all_employee_requests AS (
    SELECT 
        Employee_ID,
        ROW_NUMBER() OVER (ORDER BY random()) AS request_seq
    FROM (
        SELECT Employee_ID FROM employee_min_requests
        UNION ALL
        SELECT Employee_ID FROM additional_requests
    ) combined
    LIMIT 10500
),

-- 5. Сопоставляем уникальных читателей
unique_readers AS (
    SELECT 
        Reader_ID,
        ROW_NUMBER() OVER (ORDER BY Reader_ID) AS reader_seq
    FROM Reader
    LIMIT 10500
),

-- 6. Генерируем даты, гарантируя Due_Date > Issue_Date
date_generator AS (
    SELECT 
        ROW_NUMBER() OVER () AS row_number,
        Issue_Date,
        Issue_Date + (14 + FLOOR(RANDOM() * 7))::INT AS Due_Date
    FROM (
        SELECT 
            CURRENT_DATE - (FLOOR(RANDOM() * 1825))::INT AS Issue_Date  -- Исправлено здесь
        FROM generate_series(1, 10500)
    ) AS issues
    WHERE Issue_Date + (14 + FLOOR(RANDOM() * 7))::INT > Issue_Date  -- Убедимся в этом условии
)

-- 7. Вставляем данные
INSERT INTO Loan_Request (Reader_ID, Inventory_Number, Employee_ID, Issue_Date, Due_Date)
SELECT 
    ur.Reader_ID,
    ab.Inventory_Number,
    aer.Employee_ID,
    dg.Issue_Date,
    dg.Due_Date
FROM all_books ab
JOIN all_employee_requests aer ON ab.book_seq = aer.request_seq
JOIN unique_readers ur ON ab.book_seq = ur.reader_seq
JOIN date_generator dg ON ab.book_seq = dg.row_number;