-- Место хранения
WITH HallRooms AS (
    -- Генерируем уникальный Room_Number для каждого зала в рамках библиотеки
    SELECT 
        Hall_ID,
        ROW_NUMBER() OVER (PARTITION BY Library_ID ORDER BY Hall_ID) AS Room_Number
    FROM Hall
)
INSERT INTO Storage_Location (Hall_ID, Room_Number, Rack_Number, Shelf_Number)
SELECT 
    h.Hall_ID,
    hr.Room_Number,
    racks.rack_number,
    shelves.shelf_number
FROM 
    Hall h
JOIN HallRooms hr ON h.Hall_ID = hr.Hall_ID
CROSS JOIN LATERAL (
    SELECT generate_series(1, 5 + (h.Hall_ID * 37 % 6)) AS rack_number 
) racks
CROSS JOIN LATERAL (
    SELECT generate_series(1, 5 + (racks.rack_number * 19 % 3)) AS shelf_number
) shelves
WHERE 
    h.Hall_Type IN ('Абонемент', 'Хранилище');

