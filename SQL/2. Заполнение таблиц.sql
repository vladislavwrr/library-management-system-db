inventory_numbers AS (
    SELECT 
        'LIB-' || 
        LPAD(lib.Library_ID::TEXT, 2, '0') ||  -- Берем реальный Library_ID
        '-' || 
        LPAD(ROW_NUMBER() OVER (PARTITION BY lib.Library_ID)::TEXT, 5, '0') AS Inventory_Number,
        lib.Library_ID,
        ROW_NUMBER() OVER () AS row_num
    FROM Library lib
    CROSS JOIN generate_series(1, 700) -- 700 копий на библиотеку (пример)
    WHERE lib.Library_ID BETWEEN 1 AND 15 -- Соответствует XX в инвентарном номере
),

